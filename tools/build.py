#!/usr/bin/env python3
"""Build site/data/bundle.js from content/content.json and the latest eval report.

The site loads one script (window.DATA), so it opens from file://, from GitHub Pages and from the
local coach server alike, with no fetch calls.
"""
import json, pathlib, shutil, time

ROOT = pathlib.Path(__file__).resolve().parent.parent
content = json.loads((ROOT / "content" / "content.json").read_text())
rep_p = ROOT / "evals" / "out" / "report.json"
rep = json.loads(rep_p.read_text()) if rep_p.exists() else {"evals": [], "jev": None, "generated": "not run"}

data = dict(content)
data.pop("jev_checks", None)  # eval-only
data.pop("jev_context", None)
data["quality"] = {"generated": rep.get("generated") or time.strftime("%Y-%m-%d %H:%M"),
                   "evals": rep["evals"], "jev": rep.get("jev")}

# backup deck files for the stage
dl = ROOT / "site" / "downloads"
dl.mkdir(exist_ok=True)
for src in content["meta"].get("copy_files", []):
    s = pathlib.Path(src["from"]).expanduser()
    if s.exists():
        shutil.copy2(s, dl / src["to"])

out = ROOT / "site" / "data" / "bundle.js"
out.parent.mkdir(exist_ok=True)
out.write_text("/* generated by tools/build.py — do not edit */\nwindow.DATA=" +
               json.dumps(data, ensure_ascii=False, separators=(",", ":")) + ";\n")
print(f"wrote {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
